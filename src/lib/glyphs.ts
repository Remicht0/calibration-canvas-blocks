/**
 * Ramene un texte a l'alphabet de la mire : capitales, sans accents ni ligatures,
 * tirets typographiques reduits au trait. C'est la regle « dans la mire » de DESIGN.md.
 */
export function mireText(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[Œœ]/g, "OE")
    .replace(/[Ææ]/g, "AE")
    .replace(/ß/g, "SS")
    .replace(/[—–]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[«»“”]/g, "")
    .replace(/\s+/g, " ")
    .toUpperCase();
}

/** Largeur en cellules d'une chaine rendue en 3x5 (1 cellule de chasse). */
export const textCols = (text: string) => Math.max(0, text.length * 4 - 1);

/** Dessine une chaine en blocs pleins. Aucun anti-aliasing, aucun demi-bloc. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  unit: number,
  ox = 0,
  oy = 0,
) {
  [...text].forEach((ch, i) => {
    const g = GLYPH3x5[ch] ?? GLYPH3x5["-"]!;
    for (let y = 0; y < 5; y++) {
      for (let x = 0; x < 3; x++) {
        if (g[y]![x] === "1") {
          ctx.fillRect(ox + (i * 4 + x) * unit, oy + y * unit, unit, unit);
        }
      }
    }
  });
}
